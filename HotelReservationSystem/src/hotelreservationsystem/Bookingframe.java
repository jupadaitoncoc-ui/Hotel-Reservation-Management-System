private java.time.LocalDateTime calculateCheckout() {
        java.time.LocalDate date =
                java.time.LocalDate.parse(jTextField5.getText().trim());

        String selectedTime =
                cmbCheckInTime.getSelectedItem().toString();

        java.time.LocalTime time =
                java.time.LocalTime.parse(
                        selectedTime,
                        java.time.format.DateTimeFormatter.ofPattern("hh:mm a")
                );

        return java.time.LocalDateTime.of(date, time).plusHours(22);
    }
