    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      String username = jTextField1.getText().trim();
    String password = new String(jPasswordField1.getPassword()).trim();

    // Check if fields are empty
    if (username.isEmpty() || password.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter your username and password.",
                "Login Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        // Connect to HotelManager
        HotelManager manager = HotelManager.getInstance();

        // Check username and password in MySQL
        User user = manager.loginUser(username, password); {
        UserGUI2.setCurrentUser(user);
    }

        if (user != null) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Login successful!\nWelcome, "
                    + user.getFirstName() + "!",
                    "Welcome",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            // Open user home
            SecondFrame home = new SecondFrame(user);

            home.setLocationRelativeTo(null);
            home.setVisible(true);

            this.dispose();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Invalid username or password.",
                    "Login Failed",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Login error:\n" + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
   
              
      // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

