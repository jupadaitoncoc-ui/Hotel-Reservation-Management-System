    private void loadMyReservations() {
        if (user == null) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Logged-in user was not passed to ReservationsFrame."
    );
    return;
}
        javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel)
        reservationsTable.getModel();

    model.setRowCount(0);

    HotelManager manager = HotelManager.getInstance();

    java.util.List<Reservation> reservations =
        manager.getReservationsForUser(user.getUserID());

    if (reservations == null || reservations.isEmpty()) {
        return;
    }

    for (Reservation reservation : reservations) {

        String roomNumber =
            manager.roomNumber(reservation.getRoomID());

        double totalAmount = reservation.getTotalAmount();
        double downPayment = reservation.getDownPayment();

        double balance = Math.max(0, totalAmount - downPayment);

        String status = reservation.getStatus();

        if (status == null || status.trim().isEmpty()) {
            status = "Reserved";
        }

        model.addRow(new Object[] {
            reservation.getReservationID(),
            roomNumber,
            reservation.getCheckInDate(),
            reservation.getCheckOutDate(),
            "N/A",
            String.format("₱%.2f", totalAmount),
            String.format("₱%.2f", downPayment),
            String.format("₱%.2f", balance),
            status
        });
    }
}
      
