    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       int selectedRow = reservationsTable.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a reservation first.",
            "A MAN HOTEL",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int row = reservationsTable.convertRowIndexToModel(selectedRow);

    int reservationID = Integer.parseInt(
        reservationsTable.getModel()
            .getValueAt(row, 0).toString()
    );

        String status = reservationsTable.getModel()
    .getValueAt(row, 8).toString();

    if (status.equalsIgnoreCase("Cancelled")) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "This reservation is already cancelled.",
            "A MAN HOTEL",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String[] reasons = {
        "Change of plans",
        "Incorrect reservation dates",
        "Booked another hotel",
        "Emergency",
        "Other"
    };

    String reason = (String)
        javax.swing.JOptionPane.showInputDialog(
            this,
            "Please select a cancellation reason:",
            "Cancel Reservation",
            javax.swing.JOptionPane.QUESTION_MESSAGE,
            null,
            reasons,
            reasons[0]
        );

    if (reason == null) {
        return;
    }

    if (reason.equals("Other")) {
        reason = javax.swing.JOptionPane.showInputDialog(
            this,
            "Please enter your reason:",
            "Cancellation Reason",
            javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (reason == null || reason.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter a cancellation reason."
            );
            return;
        }

        reason = reason.trim();
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Reservation ID: " + reservationID
        + "\nReason: " + reason
        + "\n\nAre you sure you want to cancel this reservation?",
        "Confirm Cancellation",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    boolean cancelled = HotelManager.getInstance()
        .cancelReservation(reservationID, reason);

    if (cancelled) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Reservation cancelled successfully.",
            "A MAN HOTEL",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        loadMyReservations();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Cancellation failed. The reservation may not exist "
            + "or may already be cancelled.",
            "Cancellation Failed",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
   // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

